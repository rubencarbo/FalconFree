export type StageId = 'metropolis' | 'archipelago' | 'dusk' | 'jungle' | 'warzone' | 'canyon' | 'glacier' | 'cyber' | 'barcelona' | 'madrid' | 'nuevayork' | 'everest' | 'europa';

/** Tipo de mundo: ciudad o escenarios naturales / en ruinas */
export type Biome = 'city' | 'jungle' | 'war' | 'canyon' | 'ice' | 'cyber' | 'real';

type WeatherOption = ['clear' | 'rain' | 'fog' | 'storm' | 'snow', number];

export interface Stage {
  id: StageId;
  name: string;
  description: string;
  seed: number;
  /** Umbral de agua (0..1): más alto = más agua */
  waterLevel: number;
  /** Escala del ruido de agua en metros */
  waterScale: number;
  /** Probabilidad de que una manzana sea parque */
  parkChance: number;
  /** Multiplicador de alturas de edificios */
  heightMul: number;
  night: boolean;
  biome?: Biome;
  /** Climas posibles y su probabilidad (si no, los de siempre) */
  weather?: WeatherOption[];
  /** Aurora boreal permanente */
  aurora?: boolean;
  /** Etiqueta corta para tarjetas */
  tag?: string;
  /** Mundo real: id del mapa (public/real/<id>.dat) */
  real?: string;
  /** Mundo abierto: punto de salida, destino y origen de coordenadas (los datos se cargan mientras se vuela) */
  open?: { from: { name: string; lat: number; lon: number }; to: { name: string; lat: number; lon: number } };
  /** Mundo real: lugares destacados (posición en el mundo del juego, se rellenan al cargar) */
  sights?: { name: string; lat: number; lon: number }[];
  sky: { top: string; horizon: string; fog: string };
  fogDensity: number;
  sun: { color: string; intensity: number; dir: [number, number, number] };
  hemi: { sky: string; ground: string; intensity: number };
  palette: {
    buildings: string[];
    water: [string, string, string];
    grass: [string, string];
    road: string;
    sidewalk: string;
    sand: string;
    lot: string;
    window: string;
    tree: [string, string];
    cloud: string;
  };
}

